class CertificadoModel {
  final String nomeConsultor;
  final String nomeBadge;
  final String nivel;
  final String area;
  final String serviceLine;
  final String dia;
  final String mes;
  final String ano;

  CertificadoModel({
    required this.nomeConsultor,
    required this.nomeBadge,
    required this.nivel,
    required this.area,
    required this.serviceLine,
    required this.dia,
    required this.mes,
    required this.ano,
  });
}